"""Copy teammates' code into the backend so the Docker image (build context = backend/) can import it.

    python scripts/sync_vendored.py           # copy
    python scripts/sync_vendored.py --check   # exit 1 if a copy is stale (used by the tests)

Sources of truth stay where the teammates put them:
  ml/chesttriage_ml/                    (Member A)  -> backend/chesttriage_ml/      byte-identical
  eval_safety/voxelsort_eval_safety/    (Member B)  -> backend/app/evalkit/         identical except that
      flat imports ("from protocol import ...") become package-relative ("from .protocol import ...").
Never edit the copies by hand: edit the source and run this script again.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
ML_SRC = REPO / "ml" / "chesttriage_ml"
ML_DST = BACKEND / "chesttriage_ml"
EVAL_SRC = REPO / "eval_safety" / "voxelsort_eval_safety"
EVAL_DST = BACKEND / "app" / "evalkit"

EVAL_MODULES = ("urgency_mapping", "protocol", "calibration", "queue_simulator", "site_readiness", "shortcut_audit")
_FLAT = re.compile(r"^(\s*)from (%s) import " % "|".join(EVAL_MODULES), re.MULTILINE)

EVAL_INIT = '''"""Member B's evaluation and safety modules, copied from eval_safety/voxelsort_eval_safety/.

Generated by backend/scripts/sync_vendored.py. Do not edit here: the only change from B's files is
that flat imports were made package-relative. backend/tests/test_vendored_sync.py fails if a copy drifts.
"""
'''


def rewrite_eval(text: str) -> str:
    return _FLAT.sub(lambda m: f"{m.group(1)}from .{m.group(2)} import ", text)


def _norm(b: bytes) -> bytes:
    return b.replace(b"\r\n", b"\n")


def expected() -> dict[Path, bytes]:
    """Destination path -> expected bytes (LF line endings)."""
    out: dict[Path, bytes] = {}
    for src in sorted(ML_SRC.glob("*.py")):
        out[ML_DST / src.name] = _norm(src.read_bytes())
    for name in EVAL_MODULES:
        src = EVAL_SRC / f"{name}.py"
        out[EVAL_DST / src.name] = rewrite_eval(_norm(src.read_bytes()).decode("utf-8")).encode("utf-8")
    out[EVAL_DST / "__init__.py"] = EVAL_INIT.encode("utf-8")
    return out


def stale() -> list[str]:
    problems = []
    for dst, want in expected().items():
        if not dst.is_file():
            problems.append(f"missing: {dst.relative_to(BACKEND)}")
        elif _norm(dst.read_bytes()) != want:
            problems.append(f"differs from source: {dst.relative_to(BACKEND)}")
    return problems


def main() -> int:
    if not ML_SRC.is_dir() or not EVAL_SRC.is_dir():
        print("Source folders not found (ml/ and eval_safety/ must sit next to backend/).")
        return 2
    if "--check" in sys.argv:
        problems = stale()
        print("\n".join(problems) or "vendored copies are up to date")
        return 1 if problems else 0
    for dst, want in expected().items():
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(want)
        print("wrote", dst.relative_to(BACKEND))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
